--[[
	Writes ROUTE_MAP.md from the live definition:  texlua tools/offline/route_map.lua . > ROUTE_MAP.md
	(module contract table: entry/exit S, route length, elevation delta, width, hazards, gates)
]]
local root = arg[1] or "."
local H = dofile(root .. "/tools/offline/harness.lua").new(root)
local TD = H.module("ReplicatedStorage/Shared/TrackDefinitions")
local PC = H.module("ReplicatedStorage/Shared/PhysicsConfig")
local def = TD.Race
local L = TD.Generate(def, PC.Ball.Radius)
local function within(s, m)
	return s >= m.Entry.S - 1e-6 and s < m.Exit.S + 1e-6
end
local out = {}
local function w(line)
	out[#out + 1] = line
end
w("# ROUTE_MAP — " .. def.DisplayName .. " (`" .. def.Id .. "`, layout v" .. def.LayoutVersion .. ")")
w("")
w("Generated by `texlua tools/offline/route_map.lua . > ROUTE_MAP.md` from `TrackDefinitions.Race`. Do not edit by hand.")
w("")
w(string.format("Route %.0f studs · %d modules · %d checkpoints · %d hazards · %d Chaos Gates · %d grid slots · drop %.0f studs", L.Route.total, #L.Modules, #L.Checkpoints, #L.Hazards, #L.ChaosGates, #L.GridSlots, L.MaxY - L.MinY))
local est = TD.EstimateRunSeconds(L, PC.Movement, 196.2 * (PC.GravityMultiplier or 1))
w(string.format("1-D model perfect run ≈ %.0f s (full throttle, no hazards, braking or steering losses — **not a measurement**; the 90–150 s target is a playtest item).", est))
w("")
w("| # | Module | Kind | Entry S | Exit S | Length | Elev Δ | Width in→out | Hazards / features | Checkpoints | Chaos Gates |")
w("|---|---|---|---|---|---|---|---|---|---|---|")
for i, m in ipairs(L.Modules) do
	local hz, cps, gates = {}, {}, {}
	for _, h in ipairs(L.Hazards) do
		local s = h.Frame and h.Frame.S
		if s and within(s, m) then
			hz[#hz + 1] = h.Id .. " (" .. h.Kind .. ")"
		end
	end
	for _, z in ipairs(L.TrickZones) do
		if within(z.LipS, m) then
			hz[#hz + 1] = "Trick ramp"
		end
	end
	for _, p in ipairs(L.Pieces) do
		if p.Definition.Divider and p.Segment == m.Name then
			hz[#hz + 1] = "split lane (divider)"
		end
	end
	for _, c in ipairs(L.Checkpoints) do
		if within(c.S, m) then
			cps[#cps + 1] = "CP" .. c.Index .. " " .. c.Name
		end
	end
	for _, g in ipairs(L.ChaosGates) do
		if within(g.S, m) then
			gates[#gates + 1] = g.Id .. (g.Offset > 0 and " (right half)" or " (left half)")
		end
	end
	w(string.format("| %d | %s | %s | %.0f | %.0f | %.0f | %.1f | %.0f→%.0f | %s | %s | %s |", i, m.Name, m.Kind, m.Entry.S, m.Exit.S, m.RouteLength, m.ElevationDelta, m.Entry.Width, m.Exit.Width, #hz > 0 and table.concat(hz, ", ") or "—", #cps > 0 and table.concat(cps, ", ") or "—", #gates > 0 and table.concat(gates, ", ") or "—"))
end
w("")
w("## Module contract")
w("Each module = consecutive pieces sharing a `Segment`. Ports are the first/last generated cross-sections: position, forward tangent, up, width, route distance S. `TrackValidator` requires exit == next entry (≤ 0.01 studs), same facing (dot ≥ 0.9999) and width, positive route length, 8–20 grid slots, dividers that rejoin, hazards with a controller, hammer inside the lane for every seed, falling tiles passable for every seed (≥ 2 solid per row and a shared solid column between rows), sweeper speed and fan cycle in range. Hazard sockets are piece-relative (`Piece` + `At`/`From`/`To` + lateral `Offset`). Reset hooks: hazards are pure functions of (seed class, serverTime − epoch); tiles are toggled by HazardService; nothing accumulates between rounds.")
w("")
w("## Hazard seed classes")
w("Round N uses class N mod 3. Class 0 = definition values; classes 1 and 2 override (HazardSim.Variants): sweeper direction/speed, hammer period/phase, tile pattern offset/period, fan direction/timing, conveyor direction/strength, bumper phase offsets.")
print(table.concat(out, "\n"))
