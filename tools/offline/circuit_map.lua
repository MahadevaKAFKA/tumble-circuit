--[[
	Sector map of every circuit, from the live definitions:
	  texlua tools/offline/circuit_map.lua . > docs/CIRCUIT_MAPS.md
	Per circuit: lap length, model lap times, numbered sectors (gate to gate) with their route
	length, elevation change, MODEL time, hazards / route choices inside, the gate's directional
	line and its safe respawn transform. MODEL times are a 1-D rolling estimate - not playtests.
]]
local root = arg[1] or "."
local H = dofile(root .. "/tools/offline/harness.lua").new(root)
local TD = H.module("ReplicatedStorage/Shared/TrackDefinitions")
local PC = H.module("ReplicatedStorage/Shared/PhysicsConfig")

local out = {}
local function w(line)
	out[#out + 1] = line or ""
end

-- model time at every section (flying lap: start from the speed the lap ends with)
local function sectionTimes(layout)
	local m = PC.Movement
	local g = 196.2 * (PC.GravityMultiplier or 1)
	local boosts = {}
	for _, hz in ipairs(layout.Hazards) do
		if hz.Kind == "Boost" then
			boosts[#boosts + 1] = { a = hz.FromFrame.S, b = hz.ToFrame.S, accel = hz.Definition.Accel }
		end
	end
	local v = 44
	local times = { [1] = 0 }
	for pass = 1, 2 do
		local t = 0
		for i = 1, #layout.Sections - 1 do
			local a, b = layout.Sections[i], layout.Sections[i + 1]
			local ds = b.S - a.S
			local sinP = math.sin(math.rad((a.PitchDeg + b.PitchDeg) / 2))
			local throttle = v < m.ThrottleTargetSpeed and m.AlongTrackAccel * math.min(1, (m.ThrottleTargetSpeed - v) / m.ThrottleTaperRange) or 0
			local boost = 0
			for _, bz in ipairs(boosts) do
				if a.S >= bz.a and a.S < bz.b then
					boost = boost + bz.accel
				end
			end
			local accel = (5 / 7) * g * sinP + throttle + boost - (m.RollingResistance or 0) - m.LinearDrag * v
			if v > m.TerminalSpeed then
				accel = accel - math.min(m.TerminalDragMax, (v - m.TerminalSpeed) * m.TerminalDragResponse)
			end
			local vn = math.sqrt(math.max(1, v * v + 2 * accel * ds))
			t = t + ds / ((v + vn) / 2)
			v = vn
			if pass == 2 then
				times[i + 1] = t
			end
		end
	end
	return times
end

local function timeAtS(layout, times, s)
	for i = 1, #layout.Sections - 1 do
		if layout.Sections[i + 1].S >= s then
			return times[i]
		end
	end
	return times[#times]
end

w("# Circuit maps (generated)")
w("")
w("Generated by `texlua tools/offline/circuit_map.lua . > docs/CIRCUIT_MAPS.md` from the live `TrackDefinitions` circuits. Do not edit by hand.")
w("Times are a **1-D rolling MODEL** (full throttle, boost lanes, no hazards, braking, steering losses or traffic) - starting points for phone playtests, not measurements.")
for _, def in ipairs(TD.Worlds) do
	if def.Loop then
		local layout = TD.Generate(def, PC.Ball.Radius)
		local standing, flying, race = TD.EstimateLapSeconds(layout, PC.Movement, 196.2, def.Laps)
		local times = sectionTimes(layout)
		w("")
		w(string.format("## %s (`%s`, layout v%d, %d laps)", def.DisplayName, def.Id, def.LayoutVersion, def.Laps))
		w("")
		w(string.format("Lap **%.0f studs** · %d checkpoint sectors per lap · height range %.0f studs · closure error %.3f studs · model lap %.1f s standing / %.1f s flying · model race %.0f s · race clock %d s (provisional) · finish grace after the leader %d s", layout.LapLength, #layout.Checkpoints, layout.MaxY - layout.MinY, layout.ClosureError, standing, flying, race, def.MaxRaceSeconds or 0, 90))
		w("")
		w("| # | Sector (gate to gate) | From S | Length | Elev Δ | Model s | Inside this sector | Gate respawn (x, y, z) |")
		w("|---|---|---|---|---|---|---|---|")
		local gates = { { Name = "START / FINISH", S = 0, RespawnFrame = layout.LineRespawnFrame } }
		for _, cp in ipairs(layout.Checkpoints) do
			gates[#gates + 1] = cp
		end
		for i, gate in ipairs(gates) do
			local nextS = gates[i + 1] and gates[i + 1].S or layout.LapLength
			local inside = {}
			for _, hz in ipairs(layout.Hazards) do
				local s = hz.Frame and hz.Frame.S
				if s and s >= gate.S and s < nextS then
					local label = hz.Kind == "Boost" and "boost lane" or hz.Kind
					local seen = false
					for _, x in ipairs(inside) do
						seen = seen or x == label
					end
					if not seen then
						inside[#inside + 1] = label
					end
				end
			end
			for _, piece in ipairs(layout.Pieces) do
				local s0 = layout.Sections[piece.FirstSection].S
				if s0 >= gate.S and s0 < nextS then
					if piece.Definition.Kind == "SplitLane" then
						inside[#inside + 1] = "**route choice**"
					end
					if piece.Definition.HalfFloor then
						inside[#inside + 1] = "risk gap (" .. (piece.Definition.HalfFloor == "Left" and "right" or "left") .. " lane)"
					end
				end
			end
			for _, z in ipairs(layout.TrickZones) do
				if z.LipS >= gate.S and z.LipS < nextS then
					inside[#inside + 1] = "kicker"
				end
			end
			local a = layout.Sections[1]
			for _, sec in ipairs(layout.Sections) do
				if sec.S <= gate.S then
					a = sec
				end
			end
			local b = layout.Sections[#layout.Sections]
			for k = #layout.Sections, 1, -1 do
				if layout.Sections[k].S >= nextS then
					b = layout.Sections[k]
				end
			end
			local t0, t1 = timeAtS(layout, times, gate.S), timeAtS(layout, times, nextS)
			if nextS >= layout.LapLength then
				t1 = times[#times]
			end
			local r = gate.RespawnFrame and gate.RespawnFrame.Position
			w(string.format("| %d | %s → %s | %.0f | %.0f | %+.0f | %.1f | %s | %s |", i, gate.Name, gates[i + 1] and gates[i + 1].Name or "START / FINISH", gate.S, nextS - gate.S, b.Position.Y - a.Position.Y, t1 - t0, #inside > 0 and table.concat(inside, ", ") or "-", r and string.format("%.0f, %.0f, %.0f", r.X, r.Y, r.Z) or "-"))
		end
		w("")
		w("Gates are directional: a gate counts only when race distance sweeps forward across it inside the corridor (CheckpointService), in order, on every lap. Branch lanes share one progress scale (projection onto the centreline).")
	end
end
print(table.concat(out, "\n"))
